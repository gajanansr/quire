/**
 * Release tasks stop here when there is nothing to sign with.
 *
 * Without this the build succeeds and writes `app-release-unsigned.aab`, which the
 * Play Console rejects on upload — at the end of the slowest part of the process,
 * with a message about the artifact rather than about the four values that were
 * never set. Failing at the task that needed them says what to do instead.
 */
tasks.matching { it.name == "assembleRelease" || it.name == "bundleRelease" }
    .configureEach {
        doFirst {
            check(canSignRelease) {
                """
                |Cannot sign the release: no keystore credentials.
                |
                |Create $rootDir/keystore.properties (it is gitignored) with:
                |  storeFile=/absolute/path/to/quire-upload.jks
                |  storePassword=...
                |  keyAlias=quire-upload
                |  keyPassword=...
                |
                |or export QUIRE_KEYSTORE, QUIRE_KEYSTORE_PASSWORD, QUIRE_KEY_ALIAS
                |and QUIRE_KEY_PASSWORD. docs/release.md has the keytool command.
                """.trimMargin()
            }
        }
    }

// Apache PDFBox must not reach the device: it needs java.awt. Fixtures arrive as
// pre-built assets instead.
tasks.matching {
    it.name.contains("AndroidTest") && (it.name.startsWith("merge") || it.name.startsWith("generate"))
}.configureEach { dependsOn(":core:generateFixtureAssets") }
